"""Single-file build of this package for hosts that run one script (APTV).

``render()`` returns a standard-library-only script that embeds every module
source and web asset, installs an in-memory importer for ``live_direct``
(nothing is extracted to disk) and runs ``live_direct.standalone``. With a
config it also embeds those settings, so the script starts already set up.
"""
import base64
from pathlib import Path

PKG = Path(__file__).resolve().parent
ASSET_SUFFIXES = ('.html', '.js', '.css', '.svg', '.png')

TEMPLATE = '''#!/usr/bin/env python3
# Live Direct single-file build ({version}). Generated by live_direct/bundle.py;
# edit the live_direct package, not this file. License: GPL-3.0.
# Usage: python3 live-direct-aptv.py [port] [--bind ADDR] [--data-dir DIR]
import base64 as _b64
import importlib as _importlib
import importlib.abc as _abc
import importlib.util as _util
import sys as _sys

_SOURCES = {sources}
_PACKAGES = {packages}
_ASSETS = {assets}
# Settings captured when this file was exported; None for a plain build.
_CONFIG = {config}


class _Loader(_abc.Loader):
    def create_module(self, spec):
        return None

    def exec_module(self, module):
        name = module.__name__
        module.__file__ = '<live-direct-aptv>/' + name.replace('.', '/') + ('/__init__.py' if name in _PACKAGES else '.py')
        exec(compile(_SOURCES[name], module.__file__, 'exec'), module.__dict__)


class _Finder(_abc.MetaPathFinder):
    loader = _Loader()

    def find_spec(self, name, path=None, target=None):
        if name not in _SOURCES:
            return None
        spec = _util.spec_from_loader(name, self.loader, is_package=name in _PACKAGES)
        if name in _PACKAGES:
            spec.submodule_search_locations = []
        return spec


if not any(isinstance(f, _Finder) for f in _sys.meta_path):
    _sys.meta_path.insert(0, _Finder())

# importlib instead of import statements: hosts such as APTV scan a script's
# imports and would report the embedded package as a missing module.
_app = _importlib.import_module('live_direct.app')
_app.ASSETS.update({{k: _b64.b64decode(v) for k, v in _ASSETS.items()}})

if __name__ == '__main__':
    _standalone = _importlib.import_module('live_direct.standalone')
    _standalone.SCRIPT_PATH = globals().get('__file__') or ''
    _standalone.EMBEDDED_CONFIG = _CONFIG
    _standalone.main()
'''


def available():
    """False inside a single-file build, which has no package files to copy."""
    return (PKG / 'standalone.py').is_file() and (PKG / 'web').is_dir()


def render(version='unknown', config=None):
    if not available():
        raise RuntimeError('package sources unavailable')
    root = PKG.parent
    sources, packages = {}, []
    for path in sorted(PKG.rglob('*.py')):
        parts = list(path.relative_to(root).with_suffix('').parts)
        if parts[-1] == '__init__':
            parts.pop()
            packages.append('.'.join(parts))
        sources['.'.join(parts)] = path.read_text(encoding='utf-8')
    # live_direct/ itself is a namespace package (no __init__.py).
    for path in [PKG, *(d for d in PKG.rglob('*') if d.is_dir() and any(d.glob('*.py')))]:
        name = '.'.join(path.relative_to(root).parts)
        if name not in sources:
            sources[name] = ''
            packages.append(name)
    assets = {p.name: base64.b64encode(p.read_bytes()).decode() for p in sorted((PKG / 'web').iterdir())
              if p.is_file() and p.suffix in ASSET_SUFFIXES}
    version = ''.join(c for c in str(version) if c.isalnum() or c in ' .:_-')[:64] or 'unknown'
    text = TEMPLATE.format(version=version, sources=repr(sources), packages=repr(sorted(packages)),
                           assets=repr(assets), config=repr(config))
    compile(text, 'live-direct-aptv.py', 'exec')
    return text
