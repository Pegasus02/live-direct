#!/usr/bin/env python3
"""Bundle live_direct into one standard-library script for single-file hosts.

    python3 tools/build_aptv.py            # writes dist/live-direct-aptv.py

The output embeds every module source and web asset, installs an in-memory
importer for the ``live_direct`` package (nothing is extracted to disk) and
runs ``live_direct.standalone``.
"""
import base64
from pathlib import Path
import subprocess
import sys

ROOT = Path(__file__).resolve().parent.parent
PKG = ROOT / 'live_direct'
DEFAULT_OUT = ROOT / 'dist' / 'live-direct-aptv.py'

TEMPLATE = '''#!/usr/bin/env python3
# Live Direct single-file build ({version}). Generated by tools/build_aptv.py;
# edit the live_direct package, not this file. License: GPL-3.0.
# Usage: python3 live-direct-aptv.py [port] [--bind ADDR] [--data-dir DIR]
import base64 as _b64
import importlib.abc as _abc
import importlib.util as _util
import sys as _sys

_SOURCES = {sources}
_PACKAGES = {packages}
_ASSETS = {assets}


class _Loader(_abc.Loader):
    def create_module(self, spec):
        return None

    def exec_module(self, module):
        name = module.__name__
        module.__file__ = '<live-direct-aptv>/' + name.replace('.', '/') + ('/__init__.py' if name in _PACKAGES else '.py')
        exec(compile(_SOURCES[name], module.__file__, 'exec'), module.__dict__)


class _Finder(_abc.MetaPathFinder):
    loader = _Loader()

    def find_spec(self, name, path=None, target=None):
        if name not in _SOURCES:
            return None
        spec = _util.spec_from_loader(name, self.loader, is_package=name in _PACKAGES)
        if name in _PACKAGES:
            spec.submodule_search_locations = []
        return spec


if not any(isinstance(f, _Finder) for f in _sys.meta_path):
    _sys.meta_path.insert(0, _Finder())

import live_direct.app as _app  # noqa: E402
_app.ASSETS.update({{k: _b64.b64decode(v) for k, v in _ASSETS.items()}})

if __name__ == '__main__':
    import live_direct.standalone as _standalone
    _standalone.SCRIPT_PATH = globals().get('__file__') or ''
    _standalone.main()
'''


def version():
    try:
        return subprocess.run(['git', 'describe', '--always', '--dirty'], cwd=ROOT, capture_output=True, text=True, check=True).stdout.strip()
    except (OSError, subprocess.CalledProcessError):
        return 'unknown'


def build(out=DEFAULT_OUT):
    sources, packages = {}, []
    for path in sorted(PKG.rglob('*.py')):
        rel = path.relative_to(ROOT).with_suffix('')
        parts = list(rel.parts)
        if parts[-1] == '__init__':
            parts.pop()
            packages.append('.'.join(parts))
        sources['.'.join(parts)] = path.read_text(encoding='utf-8')
    # live_direct/ itself is a namespace package (no __init__.py).
    for path in [PKG, *(d for d in PKG.rglob('*') if d.is_dir() and any(d.glob('*.py')))]:
        name = '.'.join(path.relative_to(ROOT).parts)
        if name not in sources:
            sources[name] = ''
            packages.append(name)
    assets = {p.name: base64.b64encode(p.read_bytes()).decode() for p in sorted((PKG / 'web').iterdir())
              if p.is_file() and p.suffix in ('.html', '.js', '.css', '.svg', '.png')}
    text = TEMPLATE.format(version=version(), sources=repr(sources), packages=repr(sorted(packages)), assets=repr(assets))
    compile(text, str(out), 'exec')
    out = Path(out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(text, encoding='utf-8')
    return out


if __name__ == '__main__':
    target = build(Path(sys.argv[1]) if len(sys.argv) > 1 else DEFAULT_OUT)
    print(f'{target} ({target.stat().st_size // 1024} KiB)')
